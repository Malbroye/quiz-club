export function pickHomeItem(items, history) {
  const indexes = items.map((_, index) => index)
  const seen = new Set((Array.isArray(history) ? history : [history]).filter((index) => indexes.includes(index)))
  const fresh = indexes.filter((index) => !seen.has(index))
  const last = [...seen].at(-1)
  const choices = fresh.length ? fresh : indexes.filter((index) => index !== last)
  const index = choices[Math.floor(Math.random() * choices.length)] ?? 0
  return { item: items[index], history: [...(fresh.length ? seen : []), index] }
}
